import Foundation

/// One `analyseBuffer` result, as the real engine reported it.
public struct OracleFrame: Decodable, Sendable {
    public let call: Int
    public let canHearANote: Bool
    public let currentString: Int
    /// The engine's own `InTuneRatio` double. It is `g[48] / 15` with `g[48]`
    /// an integer counter, so the value is always `k/15`; `ratioNumerator` is
    /// recovered from it so the comparison can be exact rather than
    /// floating-point-approximate.
    public let inTuneRatio: Double
    public let measuredPitchHz: Double
    public let measuredPitchMidi: Int
    public let micRms: Double
    public let possibleWrongStringId: Int
    public let tuningErrorCents: Double
    public let truthHz: Double

    public var ratioNumerator: Int { Int((inTuneRatio * 15.0).rounded()) }
}

/// The recorded output of the real `WebTuna.wasm` over the coverage matrix.
///
/// Generated by `tools/oracle-trace.mjs`, which needs the wasm (Yousician's IP,
/// never committed). Only the *output numbers* are recorded — no samples and no
/// engine code — so the fixture is reviewable, and `swift test` needs neither
/// node nor the wasm to run.
public struct OracleTrace: Decodable, Sendable {
    public struct Cell: Decodable, Sendable {
        public let label: String
        public let index: Int32
        public let truthHz: Double
        public let calls: Int
        /// FNV-1a of the 3.0 s signal, as produced by the JavaScript generator.
        public let sig: String
        public let frames: [OracleFrame]
    }

    public let sampleRate: Double
    public let wasmSHA256: String
    public let cells: [Cell]

    public var sigByLabel: [String: UInt32] {
        var out: [String: UInt32] = [:]
        for c in cells { out[c.label] = UInt32(c.sig, radix: 16) ?? 0 }
        return out
    }

    public func cell(_ label: String) -> Cell? { cells.first { $0.label == label } }

    public static func load(
        from url: URL? = nil
    ) throws -> OracleTrace {
        let resolved = url ?? URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()   // WebTunaReferenceTests
            .deletingLastPathComponent()   // Tests
            .deletingLastPathComponent()   // swift-reference
            .appendingPathComponent("Fixtures/oracle-trace.json")
        return try JSONDecoder().decode(OracleTrace.self, from: try Data(contentsOf: resolved))
    }
}
